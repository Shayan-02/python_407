def sum_numbers(num1: float, num2: float) -> float:
    """
    Get tow numbers and return sum of them.

    Args:
        num1 (float): first number
        num2 (float): second number

    Returns:
        float: sum of num1 & num2
    """
    return num1 + num2

# call function
print(sum_numbers(10, 20))